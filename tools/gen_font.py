#!/usr/bin/env python3
"""Regenerate src/core/font_cp437.h from a 4096-byte 8x16 VGA font (.F16).

usage: python3 tools/gen_font.py path/to/CP437.F16 > src/core/font_cp437.h
"""
import sys

data = open(sys.argv[1], 'rb').read()
if len(data) != 4096:
    sys.exit("expected a 4096-byte 8x16 font, got %d bytes" % len(data))
print("/* CP437 8x16 bitmap font, 256 glyphs x 16 rows, one byte per row,")
print(" * MSB = leftmost pixel. Generated by tools/gen_font.py from the")
print(" * Moebius editor's CP437.F16 (Apache-2.0, see LICENSE-moebius.txt). */")
print("#ifndef FONT_CP437_H\n#define FONT_CP437_H\n")
print("#define FONT_W 8\n#define FONT_H 16\n")
print("static const unsigned char font_cp437[256 * 16] = {")
for g in range(256):
    row = data[g * 16:(g + 1) * 16]
    print("    " + ", ".join("0x%02x" % b for b in row) + ",  /* 0x%02x */" % g)
print("};\n\n#endif")
